#!/usr/bin/env node
// Generates the docs.levimc.org root site in site/ (what .github/workflows/deploy.yml publishes) from the
// canonical levimc-kit in kit/ and the legacy redirect table in scripts/legacy-redirects.mjs.
// No dependencies (Node 24; any Node >= 22).
//
//   node scripts/build-site.mjs              (re)write site/
//   node scripts/build-site.mjs --check      exit 1 when site/ is not what the generator produces (CI)
//   node scripts/build-site.mjs --out <dir>  write somewhere else
//
// Output:
//   site/index.html          instant redirect to https://levimc.org/ (kit static page as the no-JS fallback)
//   site/404.html            kit static 404; a forwarding map runs first (legacy URLs, wrongly cased projects)
//   site/<old site>/…        one redirect page per legacy URL (scripts/legacy-redirects.mjs)
//   site/_kit/…              the kit assets these pages reference (kit.css, kit.js, sprites)
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { MOVED_SITES, ORIGIN, PROJECT_SITES } from './legacy-redirects.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const KIT_STATIC = join(repo, 'kit', 'static');
/** Where the pages load kit assets from (site/_kit/ → https://docs.levimc.org/_kit/). */
export const ASSET_BASE = '/_kit/';
const KIT_TEMPLATE_BASE = '/levimc-kit/';
const BANNER = '<!-- generated by scripts/build-site.mjs from kit/static — do not edit; run `node scripts/build-site.mjs` -->';

// ------------------------------------------------------------------------------------------------ routing
// Both functions are also inlined into site/404.html (Function#toString, whitespace collapsed), so they stay
// ES5 and contain no comments.

/** Normalises the part of an old URL below the old site root to a page key ("zh-CN/api/hook.html" → "zh-cn/api/hook"). */
export function legacyKey(rest) {
  return rest
    .toLowerCase()
    .replace(/\/+$/, '')
    .replace(/(^|\/)index(\.html)?$/, '')
    .replace(/\.html$/, '')
    .replace(/\/+$/, '')
    .replace(/^\/+/, '');
}

/**
 * Where site/404.html forwards a request, or null to show the 404 page: old URLs of a moved site go to the
 * new page (or the locale home); wrongly cased project paths (/levilamina/x) go to the project
 * (/LeviLamina/x), because project sites are case-sensitive on GitHub Pages.
 * @param {string} pathname location.pathname (percent-encoded)
 * @param {string} search location.search
 * @param {string} hash location.hash
 * @param {{ o: string, m: { f: string, t: string, p: Record<string, [string, number]>, d: [string, string][] }[], c: string[] }} D
 */
export function legacyForward(pathname, search, hash, D) {
  var path = pathname;
  try {
    path = decodeURIComponent(pathname);
  } catch (e) {
    path = pathname;
  }
  var lower = path.toLowerCase();
  for (var i = 0; i < D.m.length; i++) {
    var site = D.m[i];
    if (lower !== site.f.slice(0, -1) && lower.indexOf(site.f) !== 0) continue;
    var key = legacyKey(lower.slice(site.f.length));
    if (Object.prototype.hasOwnProperty.call(site.p, key)) return D.o + site.t + site.p[key][0] + (site.p[key][1] ? hash : '');
    for (var j = 0; j < site.d.length; j++) {
      var prefix = site.d[j][0];
      if (!prefix || key === prefix || key.indexOf(prefix + '/') === 0) return D.o + site.t + site.d[j][1];
    }
  }
  var parts = pathname.split('/');
  var first = path.split('/')[1] || '';
  for (var k = 0; k < D.c.length; k++) {
    var name = D.c[k];
    if (first !== name && first.toLowerCase() === name.toLowerCase()) return D.o + '/' + name + '/' + parts.slice(2).join('/') + search + hash;
  }
  return null;
}

/** The compact table legacyForward() reads. */
export function forwardTable() {
  return {
    o: ORIGIN,
    m: MOVED_SITES.map((s) => {
      const p = {};
      for (const [from, to, , , keepHash] of s.pages) p[legacyKey(from)] = [to, keepHash ? 1 : 0];
      for (const [from, to] of s.aliases ?? []) if (!Object.hasOwn(p, legacyKey(from))) p[legacyKey(from)] = [to, 0];
      return { f: s.from.toLowerCase(), t: s.to, p, d: (s.fallbacks ?? [['', '']]).map(([from, to]) => [legacyKey(from), to]) };
    }),
    c: PROJECT_SITES,
  };
}

/** Old page key → the file GitHub Pages serves for it ("" → index.html, "api/hook" → api/hook.html). */
export function stubFile(siteFrom, page) {
  const dir = siteFrom.replace(/^\/|\/$/g, '');
  if (page === '' || page.endsWith('/')) return `${dir}/${page}index.html`;
  return `${dir}/${page}.html`;
}

// ------------------------------------------------------------------------------------------------ pages
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const scriptJson = (v) => JSON.stringify(v).replace(/</g, "\\u003c");
/** Function source on one line (the inlined functions have no comments and no ASI-sensitive line breaks). */
const inline = (fn) => fn.toString().replace(/\n\s*/g, ' ');
const kitFiles = new Map();
/** A kit/static text file (cached: every redirect page reuses the same snippets). */
const read = (rel) => {
  if (!kitFiles.has(rel)) kitFiles.set(rel, readFileSync(join(KIT_STATIC, rel), 'utf8'));
  return kitFiles.get(rel);
};
/** Drop the "generated by build-static.mjs" banner line of a kit snippet. */
const snippet = (rel) => read(rel).replace(/^<!--[^\n]*-->\n/, '').trim();

/** The kit GlobalBar for docs.levimc.org (`current: 'docs'`, optional `currentDocs`) in a UI locale. */
export function globalBar(locale, currentDocs) {
  let html = snippet(`i18n/globalbar.${locale}.html`);
  // Same attributes GlobalBar.tsx renders for current="docs" / currentDocs (aria-current="page").
  html = html.replace('<summary class="kit-gbar-link">', '<summary class="kit-gbar-link" aria-current="page">');
  if (currentDocs) {
    const item = `<a href="${ORIGIN}/${currentDocs}/" class="kit-gbar-docs-item">`;
    html = html.split(item).join(`<a href="${ORIGIN}/${currentDocs}/" class="kit-gbar-docs-item" aria-current="page">`);
  }
  return html;
}

const footer = (locale) => snippet(`i18n/footer.${locale}.html`);

/** A kit sprite from kit/static/icons as inline SVG (inherits currentColor, like the React PixelIcon). */
function inlineIcon(name) {
  return read(`icons/${name}.svg`)
    .trim()
    .replace(' xmlns="http://www.w3.org/2000/svg"', '')
    .replace(/<title>[^<]*<\/title>/, '')
    .replace(/^<svg\b([^>]*)>/, '<svg$1 focusable="false" class="kit-pixel-icon" aria-hidden="true">');
}

/** Replace exactly one occurrence (a kit template that changed shape fails loudly instead of drifting). */
function replaceOnce(html, from, to, what) {
  const n = typeof from === 'string' ? html.split(from).length - 1 : (html.match(new RegExp(from.source, 'g')) ?? []).length;
  if (n !== 1) throw new Error(`kit/static/pages/404.html changed shape: expected one ${what}, found ${n}`);
  return html.replace(from, () => to);
}

const kitTemplate = (name) => read(`pages/${name}`).split(KIT_TEMPLATE_BASE).join(ASSET_BASE);

/** Put redirect tags right after <meta charset>, before any stylesheet, so the redirect is instant. */
function hoistIntoHead(html, tags) {
  const charset = '<meta charset="utf-8">';
  if (!html.includes(charset)) throw new Error('template without <meta charset="utf-8">');
  return html.replace(charset, () => `${charset}\n  ${BANNER}\n  ${tags.join('\n  ')}`);
}

function indexPage() {
  let html = kitTemplate('index.html');
  const redirect = [
    '<link rel="canonical" href="https://levimc.org/">',
    '<meta http-equiv="refresh" content="0; url=https://levimc.org/">',
    '<script>location.replace("https://levimc.org/");</script>',
  ];
  for (const tag of redirect) {
    if (!html.includes(tag)) throw new Error(`kit/static/pages/index.html lost ${tag}`);
    html = html.replace(new RegExp(`\\n\\s*${tag.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`), '');
  }
  return hoistIntoHead(html, redirect);
}

function notFoundPage() {
  const html = kitTemplate('404.html');
  const script =
    `<script>(function(){${inline(legacyKey)}${inline(legacyForward)}` +
    `try{var u=legacyForward(location.pathname,location.search,location.hash,${scriptJson(forwardTable())});` +
    `if(u&&u!==location.href){var d=document.documentElement;d.style.visibility="hidden";` +
    `setTimeout(function(){d.style.visibility=""},3000);location.replace(u)}}catch(e){}})();</script>`;
  return hoistIntoHead(html, [script]);
}

// Text of the redirect pages (visible only without JavaScript or for the moment before the redirect).
// Same structure as the kit's root redirect page: the heading links the target.
const STUB_TEXT = {
  en: {
    title: (page) => `Moved: ${page} | LeviMC Docs`,
    eyebrow: 'Page moved',
    heading: (link) => `Redirecting to ${link}…`,
    text: (s) => `The ${s.oldName} docs are now part of the ${s.newName} documentation.`,
    button: 'Continue',
  },
  'zh-CN': {
    title: (page) => `已迁移：${page} | LeviMC Docs`,
    eyebrow: 'Page moved',
    heading: (link) => `正在跳转到 ${link}…`,
    text: (s) => `${s.oldName} 文档已并入 ${s.newName} 文档。`,
    button: '继续',
  },
};

/**
 * A redirect page: the kit's static 404 page (same head, backdrop and shell) with the GlobalBar and footer in
 * the page's language, a "Redirecting to …" card instead of the project grid, and the redirect tags first.
 */
function stubPage(site, [, to, lang, pageTitle, keepHash], notFound) {
  const url = ORIGIN + site.to + to;
  const t = STUB_TEXT[lang];
  if (!t) throw new Error(`no stub text for ${lang}`);
  const link = `<a href="${esc(url)}">${esc(pageTitle)}</a>`;
  const main = `<main id="kit-main" class="kit-static-main">
    <section class="kit-static-card px-card kit-painted">
      <div class="kit-notfound-compass kit-slot" aria-hidden="true"><img src="${ASSET_BASE}icons/pickaxe.svg" width="64" height="64" alt="" class="pixelated"></div>
      <p class="kit-pixel-label kit-static-eyebrow">${esc(t.eyebrow)}</p>
      <h1 class="kit-static-title">${t.heading(link)}</h1>
      <p class="kit-static-text">${esc(t.text(site))}</p>
      <p class="kit-static-actions"><a class="mc-btn mc-btn-primary" href="${esc(url)}">${esc(t.button)}${inlineIcon('arrow-right')}</a></p>
    </section>
  </main>`;
  let html = notFound;
  html = replaceOnce(html, '<html lang="en">', `<html lang="${esc(lang)}">`, '<html lang="en">');
  html = replaceOnce(html, /<title>[^<]*<\/title>/, `<title>${esc(t.title(pageTitle))}</title>`, '<title>');
  html = replaceOnce(html, /\n\s*<meta name="robots" content="noindex">/, '', 'robots meta');
  html = replaceOnce(html, globalBar('en'), globalBar(lang, site.to.replace(/\//g, '')), 'GlobalBar');
  html = replaceOnce(html, footer('en'), footer(lang), 'footer');
  html = replaceOnce(html, /<main id="kit-main" class="kit-static-main">[\s\S]*?<\/main>/, main, '<main>');
  return hoistIntoHead(html, [
    `<link rel="canonical" href="${esc(url)}">`,
    `<meta http-equiv="refresh" content="0; url=${esc(url)}">`,
    `<script>location.replace(${scriptJson(url)}${keepHash ? '+location.hash' : ''});</script>`,
  ]);
}

// ------------------------------------------------------------------------------------------------ build
/** Every file the generator owns, as site-relative path → contents. */
export function generate() {
  const files = new Map();
  const notFound = kitTemplate('404.html');
  files.set('index.html', indexPage());
  files.set('404.html', notFoundPage());
  for (const site of MOVED_SITES) {
    for (const entry of site.pages) {
      const file = stubFile(site.from, entry[0]);
      if (files.has(file)) throw new Error(`duplicate legacy page ${file}`);
      files.set(file, stubPage(site, entry, notFound));
    }
  }
  // Copy exactly the kit assets the pages reference.
  const assets = new Set();
  for (const html of files.values()) for (const m of html.matchAll(/["'(]\/_kit\/([^"')\s?#]+)/g)) assets.add(m[1]);
  for (const rel of [...assets].sort()) files.set(`_kit/${rel}`, readFileSync(join(KIT_STATIC, rel)));
  return files;
}

/** Top-level entries of site/ that the generator owns completely. */
export function ownedRoots() {
  const roots = MOVED_SITES.map((s) => {
    if (!/^\/[A-Za-z0-9._-]+\/$/.test(s.from) || /^\/(_kit|\.+)\/$/.test(s.from)) throw new Error(`MOVED_SITES.from must be one path segment like "/old-site/": ${s.from}`);
    return s.from.slice(1, -1);
  });
  return ['index.html', '404.html', '_kit', ...roots];
}

function listFiles(dir) {
  try {
    return readdirSync(dir, { recursive: true, withFileTypes: true })
      .filter((e) => e.isFile())
      .map((e) => relative(dir, join(e.parentPath, e.name)).split(sep).join('/'));
  } catch {
    return [];
  }
}

function main() {
  const args = process.argv.slice(2);
  const outArg = args.includes('--out') ? args[args.indexOf('--out') + 1] : join(repo, 'site');
  if (!outArg || outArg.startsWith('--')) {
    console.error('Usage: node scripts/build-site.mjs [--check] [--out <dir>]');
    process.exit(2);
  }
  const out = resolve(outArg);
  const files = generate();
  const roots = ownedRoots();
  const owned = (rel) => roots.some((r) => rel === r || rel.startsWith(r + '/'));
  if (args.includes('--check')) {
    const problems = [];
    for (const [rel, body] of files) {
      let disk = null;
      try {
        disk = readFileSync(join(out, rel));
      } catch {
        /* missing */
      }
      if (!disk) problems.push(`missing  ${rel}`);
      else if (!disk.equals(Buffer.isBuffer(body) ? body : Buffer.from(body))) problems.push(`stale    ${rel}`);
    }
    for (const rel of listFiles(out)) if (owned(rel) && !files.has(rel)) problems.push(`extra    ${rel}`);
    if (problems.length) {
      console.error(`site/ is out of date (${problems.length}); run \`node scripts/build-site.mjs\` and commit:\n  ${problems.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`site/ is up to date (${files.size} generated files)`);
    return;
  }
  for (const root of roots) rmSync(join(out, root), { recursive: true, force: true });
  for (const [rel, body] of files) {
    mkdirSync(dirname(join(out, rel)), { recursive: true });
    writeFileSync(join(out, rel), body);
  }
  console.log(`wrote ${files.size} files to ${relative(process.cwd(), out) || out}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
